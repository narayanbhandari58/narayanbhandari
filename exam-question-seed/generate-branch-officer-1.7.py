def make_q(unit, n, level, text, correct, distractors, kind):
    opts=[correct]+distractors[:3]
    k=(n-1)%4
    opts=opts[-k:]+opts[:-k] if k else opts
    return {"id":f"{unit}-{n:03d}","unit":unit,"level":level,"type":kind,"question":text,"options":opts,"correct":opts.index(correct),"solution":""}

